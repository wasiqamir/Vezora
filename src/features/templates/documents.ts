import {
  CURRENT_SCHEMA_VERSION,
  type ProjectDocument,
  type ProjectObject,
} from "@/features/projects/document";
import type { TemplateCategoryLabel } from "@/features/templates/catalog";

export type StarterTemplate = {
  slug: string;
  name: string;
  category: TemplateCategoryLabel;
  description: string;
  document: ProjectDocument;
};

type ObjectInput = Pick<ProjectObject, "id" | "type" | "name" | "x" | "y" | "width" | "height"> &
  Partial<ProjectObject>;

function item(input: ObjectInput): ProjectObject {
  return {
    scaleX: 1,
    scaleY: 1,
    angle: 0,
    opacity: 1,
    visible: true,
    locked: false,
    ...input,
  };
}

function text(input: {
  id: string;
  name: string;
  text: string;
  x: number;
  y: number;
  width: number;
  fontSize: number;
  fill: string;
  fontId?: string;
  fontFamily?: string;
  fontWeight?: number;
  letterSpacing?: number;
  textAlign?: "left" | "center" | "right";
}): ProjectObject {
  return item({
    id: input.id,
    type: "text",
    name: input.name,
    text: input.text,
    x: input.x,
    y: input.y,
    width: input.width,
    height: Math.round(input.fontSize * 1.2),
    fill: input.fill,
    fontId: input.fontId ?? "outfit",
    fontFamily: input.fontFamily ?? "Outfit",
    fontSize: input.fontSize,
    fontWeight: input.fontWeight ?? 500,
    letterSpacing: input.letterSpacing ?? 0,
    lineHeight: 1.16,
    textAlign: input.textAlign ?? "left",
  });
}

function document(
  preset: ProjectDocument["artboard"]["preset"],
  width: number,
  height: number,
  background: string,
  objects: ProjectObject[],
): ProjectDocument {
  return {
    schemaVersion: CURRENT_SCHEMA_VERSION,
    artboard: { preset, width, height, background },
    objects,
  };
}

